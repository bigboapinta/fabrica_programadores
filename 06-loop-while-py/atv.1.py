numero = int(input("Digite um número para ver a tabuada: "))
i = int(input("Digite até qual número você quer ver a tabuada: "))
f = int(input("Digite o número de vezes que você quer ver a tabuada: "))
while i <= f :
    print(f"{numero} x {i} = {numero  * i }")
    i += 1
   








